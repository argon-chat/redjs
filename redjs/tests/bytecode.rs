//! Real JSC cache generation/consumption, including cross-VM ownership.
//! Synthetic or corrupted payloads are tested only at the envelope boundary.
use redjs::api::{Context, Error, HostArgs, Value};
use redjs::bytecode::Bytecode;
use std::mem::ManuallyDrop;

#[test]
fn bytecode_classic_script_roundtrip() {
    // Current JSC contexts live for the process lifetime; avoid the separately
    // tracked teardown issue when this test exits on either success or panic.
    let compiler = ManuallyDrop::new(Context::new());
    let url = "sk://bytecode/π.js";
    let source = r#"
        globalThis.__cacheRuns = (globalThis.__cacheRuns || 0) + 1;
        globalThis.__cacheFactory = function makeGreeter(prefix) {
            return class Greeter {
                #name = 'π😀';
                read(suffix = '!') { return prefix + this.#name + suffix; }
            };
        };
        __cacheRuns;
    "#;
    let cache = compiler.compile_bytecode(source, url).unwrap();
    assert_eq!(
        compiler.eval("typeof __cacheRuns").unwrap_string(&compiler),
        "undefined"
    );
    let key = compiler.bytecode_cache_key(source, url);
    assert_eq!(cache.cache_key(), key);
    let serialized = cache.as_bytes().to_vec();
    assert!(serialized.len() > 96);
    drop(cache);

    let ctx = ManuallyDrop::new(Context::new());
    assert_eq!(ctx.bytecode_cache_key(source, url), key);
    let imported = unsafe { Bytecode::from_trusted_bytes(&serialized, key) }.unwrap();
    let (value, used) = ctx
        .eval_named_with_bytecode(source, url, Some(&imported))
        .unwrap();
    assert!(used, "fresh VM must consume generated bytecode");
    assert_eq!(ctx.to_number(value).unwrap(), 1.0);
    drop(imported);
    drop(serialized);
    // The source provider/decoder must keep its owned bytes, including after
    // the Rust cache dies and the first GC precedes a lazy function call.
    ctx.gc();
    assert_eq!(
        ctx.eval("new (__cacheFactory('hello '))().read('?')")
            .unwrap_string(&ctx),
        "hello π😀?"
    );
    assert!(ctx
        .eval("String(__cacheFactory).includes('makeGreeter')")
        .unwrap()
        .as_bool()
        .unwrap());

    // Exact source and URL mismatches are rejected before reaching the decoder.
    let cache = compiler.compile_bytecode("40 + 2", "sk://a.js").unwrap();
    let (value, used) = ctx
        .eval_named_with_bytecode("40 + 3", "sk://a.js", Some(&cache))
        .unwrap();
    assert!(!used);
    assert_eq!(ctx.to_number(value).unwrap(), 43.0);
    let (value, used) = ctx
        .eval_named_with_bytecode("40 + 2", "sk://b.js", Some(&cache))
        .unwrap();
    assert!(!used);
    assert_eq!(ctx.to_number(value).unwrap(), 42.0);
    assert!(unsafe { Bytecode::from_trusted_bytes(cache.as_bytes(), key) }.is_none());
    let mut corrupted = cache.as_bytes().to_vec();
    *corrupted.last_mut().unwrap() ^= 1;
    assert!(unsafe { Bytecode::from_trusted_bytes(&corrupted, cache.cache_key()) }.is_none());
    assert!(
        unsafe { Bytecode::from_trusted_bytes(&cache.as_bytes()[..40], cache.cache_key()) }
            .is_none()
    );

    let throwing = "globalThis.__beforeThrow = (globalThis.__beforeThrow || 0) + 1; throw new Error('cached throw');";
    let cache = compiler
        .compile_bytecode(throwing, "sk://throws.js")
        .unwrap();
    let result = ctx.eval_named_with_bytecode(throwing, "sk://throws.js", Some(&cache));
    let Err(Error::Exception(exception)) = result else {
        panic!("expected JS exception: {result:?}")
    };
    assert!(ctx
        .to_rust_string(exception)
        .unwrap()
        .contains("cached throw"));
    assert_eq!(
        ctx.to_number(ctx.eval("__beforeThrow").unwrap()).unwrap(),
        1.0
    );

    // Recursive mode serializes nested bodies as well; a distinct VM must
    // still install its own global references and call Rust host callbacks.
    let recursive = "globalThis.__nested = x => () => hostTimesSeven(x); 42;";
    let cache = compiler
        .compile_bytecode_recursive(recursive, "sk://recursive.js")
        .unwrap();
    let other = ManuallyDrop::new(Context::new());
    let host = other
        .function("hostTimesSeven", 1, |_global, frame| {
            let args = unsafe { HostArgs::new(frame) };
            Value::number(args.arg(0).as_number().unwrap_or(0.0) * 7.0).0
        })
        .unwrap();
    other.global_set("hostTimesSeven", host).unwrap();
    let (value, used) = other
        .eval_named_with_bytecode(recursive, "sk://recursive.js", Some(&cache))
        .unwrap();
    assert!(used);
    assert_eq!(other.to_number(value).unwrap(), 42.0);
    drop(cache);
    other.gc();
    assert_eq!(
        other
            .to_number(other.eval("__nested(6)()").unwrap())
            .unwrap(),
        42.0
    );

    let bundled = "(function () { globalThis.__depthOne = () => 42; return __depthOne(); })()";
    let cache = compiler
        .compile_bytecode_with_depth(bundled, "sk://bundle.js", 1)
        .unwrap();
    let (value, used) = ctx
        .eval_named_with_bytecode(bundled, "sk://bundle.js", Some(&cache))
        .unwrap();
    assert!(used);
    assert_eq!(ctx.to_number(value).unwrap(), 42.0);

    let result = compiler.compile_bytecode("function (", "sk://invalid.js");
    assert!(matches!(result, Err(Error::Exception(_))));
}

trait StringValue {
    fn unwrap_string(self, context: &Context) -> String;
}

impl StringValue for redjs::api::Result<redjs::api::Value> {
    fn unwrap_string(self, context: &Context) -> String {
        context.to_rust_string(self.unwrap()).unwrap()
    }
}
